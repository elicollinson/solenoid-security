"""Shared stdlib helpers for the varied prompt-injection cohort importers.

Each importer pins upstream files by SHA-256, builds canonical-jsonl cases with
stable IDs, origin-tagged turns, labels, facets and text hashes, and then either
verifies the generated bytes against the tracked manifest (default) or, with
--write-manifest, records a new manifest revision. Generated case text is only
written under ignored evals/private/. No importer calls a model.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LABELS = ("injection", "benign")
# Engine bound in evals/src/engines.ts: prompt bytes + source bytes + 1,280 <= 65,536.
# The score-only prompt is ~290 bytes, so ~63,966 source bytes fit; keep a margin.
# The longest existing LongPIBench paper is 61,278 bytes.
MAX_SCREENED_BYTES = 63000


def digest(data):
    return hashlib.sha256(data).hexdigest()


def text_digest(text):
    return digest(text.encode("utf8"))


def read_pinned(path, expected, label=None):
    """Read bytes and reject any file whose SHA-256 differs from its pin."""
    data = Path(path).read_bytes()
    if digest(data) != expected:
        raise ValueError(f"Upstream SHA-256 mismatch: {label or path}")
    return data


def verify_files(directory, pins):
    for name, expected in pins.items():
        read_pinned(Path(directory) / name, expected, name)


def make_case(case_id, label, turns, facets):
    if label not in LABELS:
        raise ValueError(f"Invalid label for {case_id}")
    if not turns or len({turn["id"] for turn in turns}) != len(turns):
        raise ValueError(f"Invalid turns for {case_id}")
    for turn in turns:
        if not isinstance(turn["text"], str) or turn.get("origin") not in ("operator", "agent", "external"):
            raise ValueError(f"Invalid turn in {case_id}")
    external = [turn for turn in turns if turn["origin"] == "external"]
    if not external or not external[-1]["text"].strip():
        raise ValueError(f"Case lacks screened external text: {case_id}")
    if len(external[-1]["text"].encode("utf8")) > MAX_SCREENED_BYTES:
        raise ValueError(f"Screened text exceeds local engine bound: {case_id}")
    for key, value in facets.items():
        ok = isinstance(value, (str, bool)) or isinstance(value, int) or isinstance(value, float) or (isinstance(value, list) and all(isinstance(item, str) for item in value))
        if not ok:
            raise ValueError(f"Invalid facet {key} in {case_id}")
    text = "\n".join(turn["text"] for turn in turns)
    return {"id": case_id, "label": label, "turns": turns, "facets": facets, "text_sha256": text_digest(text)}


def unique_screened(cases):
    """Keep the first case for each exact screened (last external) text.

    Full-text last_external screening sends only that turn, so later duplicates
    would repeat an identical model input. Returns (kept cases, dropped count).
    """
    seen, kept = set(), []
    for case in cases:
        key = [turn for turn in case["turns"] if turn["origin"] == "external"][-1]["text"]
        if key in seen:
            continue
        seen.add(key)
        kept.append(case)
    return kept, len(cases) - len(kept)


def canonical_bytes(cases):
    if len({case["id"] for case in cases}) != len(cases):
        raise ValueError("Duplicate case IDs")
    return "".join(json.dumps(case, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n" for case in cases).encode("utf8")


def class_counts(cases):
    return {label: sum(case["label"] == label for case in cases) for label in LABELS}


def manifest_path(dataset_id):
    return ROOT / "evals" / "datasets" / f"{dataset_id}.json"


def source_path(dataset_id):
    return f"evals/private/sources/{dataset_id}.jsonl"


def emit(dataset_id, cases, provenance, write_manifest=False, root=ROOT):
    """Verify (or record) the manifest pin, then write ignored canonical JSONL."""
    data = canonical_bytes(cases)
    actual = digest(data)
    counts = class_counts(cases)
    path = manifest_path(dataset_id)
    if write_manifest:
        manifest = {
            "schemaVersion": "security-eval-dataset/v1",
            "id": dataset_id,
            "revision": f"sha256:{actual}",
            "source": {"path": source_path(dataset_id), "sha256": actual, "format": "canonical-jsonl", "visibility": "public"},
            "expectedCases": len(cases),
            "annotationKey": "prompt_injection_attempt",
            "positiveValues": ["injection"],
            "negativeValues": ["benign"],
            "provenance": {**provenance, "classCounts": counts},
        }
        path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    manifest = json.loads(path.read_text())
    if actual != manifest["source"]["sha256"] or len(cases) != manifest["expectedCases"] or manifest["provenance"].get("classCounts") != counts:
        raise ValueError(f"{dataset_id} canonical manifest mismatch: sha256:{actual} cases={len(cases)} {counts}")
    output = Path(root) / manifest["source"]["path"]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(data)
    print(json.dumps({"datasetId": dataset_id, "cases": len(cases), "classes": counts, "sha256": actual}))
    return actual
